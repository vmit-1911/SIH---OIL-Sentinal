    def _build_header_banner(self, title: str, subtitle: str, metadata_items: List[tuple]) -> List[Any]:
        """Create a standardized enterprise document header banner."""
        elements = []
        elements.append(Paragraph(title, self.styles["DocTitle"]))
        elements.append(Spacer(1, 2))
        elements.append(Paragraph(subtitle, self.styles["DocSubtitle"]))
        elements.append(Spacer(1, 8))

        # Metadata table
        meta_data = []
        row = []
        for i, (label, val) in enumerate(metadata_items):
            cell_content = [
                Paragraph(label.upper(), self.styles["MetaLabel"]),
                Paragraph(str(val), self.styles["MetaValue"]),
            ]
            row.append(cell_content)
            if len(row) == 4 or i == len(metadata_items) - 1:
                while len(row) < 4:
                    row.append("")
                meta_data.append(row)
                row = []

        col_w = 504 / 4
        t = Table(meta_data, colWidths=[col_w] * 4)
        t.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), self.c_light_bg),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ]))
        elements.append(t)
        elements.append(Spacer(1, 10))
        return elements

